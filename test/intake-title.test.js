// כותרת האירוע האישי (H3, docs/08-chapter8/65, 27.10.2026): "הכותרת = המילים של יובל בלי תאריך ושעה".
// לפני התיקון הכותרת הייתה רק מילות האירוע שבמילון ("תור לספר מחר ב-17:00" -> "תור"). 27.10.2026 הוא יום שלישי, 17:00 בישראל.
import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import { extractFacts } from '../lib/intake-facts.js';

const topicOf = (text, forcedType) => extractFacts({ text, receivedAt: new Date('2026-10-27T14:00:00Z'), channel: 'app', timetable: [], timezone: 'Asia/Jerusalem', forcedType })
  .facts.find((fact) => fact.field === 'topic')?.value;

describe('כותרת אירוע אישי: המילים של יובל בלי תאריך ושעה (H3, 65)', () => {
  for (const [text, title] of [
    ['תור לספר מחר ב-17:00', 'תור לספר'],
    ['תור למספרה מחר ב-17:00', 'תור למספרה'],
    ['תור לרופא שיניים היום ב-18:30', 'תור לרופא שיניים'],
    ['בדיקה רפואית היום ב-16:00', 'בדיקה רפואית'],
    ['יש לי תור לספר מחר ב-17:00', 'תור לספר'],
    ['תור לספר ב-17:00', 'תור לספר'],
    ['תור לספר ב-17:00 ואז אימון', 'תור לספר'],
    ['תור לספר מחרתיים בשעה 16:00', 'תור לספר'],
    ['ותור לרופא מחר ב-17:00', 'תור לרופא'],
    ['תור לספר ביום חמישי ב-17:00', 'תור לספר'],
    ['תור לספר יום חמישי ב-17:00', 'תור לספר'],
    ['תור לספר ב-29.10 ב-17:00', 'תור לספר'],
  ]) {
    test(`"${text}" -> "${title}"`, () => assert.equal(topicOf(text), title));
  }

  // שלושת אלה לא מזוהים אוטומטית (השעה לא צמודה לביטוי: פסיק, "אחר", או יותר מ-4 מילים), ולכן נבדקים כשהסוג נבחר ידנית ("מה זה?"), כמו בשאלת הסוג.
  test('סימן פיסוק עוצר את הכותרת', () => assert.equal(topicOf('תור לספר, מחר ב-17:00', 'personal_event'), 'תור לספר'));
  test('"ואחר כך" עוצר את הכותרת', () => assert.equal(topicOf('תור לספר ואחר כך אימון ב-17:00', 'personal_event'), 'תור לספר'));
  test('יותר מ-8 מילים לפני התאריך: 8 המילים הראשונות בלבד', () => {
    assert.equal(topicOf('תור לספר של השכונה ליד הבית של סבתא בקצה הרחוב מחר ב-17:00', 'personal_event'), 'תור לספר של השכונה ליד הבית של סבתא');
  });
});
