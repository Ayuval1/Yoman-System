// בדיקות ל-lib/intake-text.js: ניקוי טקסט עברי, פיצול למילים, והתאמת שורשים לכל ההטיות (03-intake-rules.md:122-154, 224-254).
// כל המשפטים והמילים כאן מומצאים. אין שמות אנשים, טלפונים או הודעות אמיתיות.
import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import { fin, unfin, cleanText, tokenize, matchesRoot, matchesInfinitive, ROOTS, nounRegex } from '../lib/intake-text.js';

const words = (text) => tokenize(text).tokens.map((token) => token.w);

describe('intake-text: ניקוי ופיצול', () => {
  test('אותיות סופיות מנורמלות ומוחזרות לתצוגה', () => {
    assert.equal(fin('מבחן ושלום'), 'מבחנ ושלומ');
    assert.equal(unfin('בוחנ'), 'בוחן');
    assert.equal(unfin('מתמטיקה'), 'מתמטיקה'); // לא נוגע במילה שלא נגמרת באות שיש לה סופית
  });
  test('ש.ב ושיעורים נהפכים לשיעורי בית; גרשיים בתוך מילה מחוברים', () => {
    assert.deepEqual(words('ש.ב במתמטיקה'), ['שיעורי', 'בית', 'במתמטיקה']);
    assert.deepEqual(words('ש"ב'), ['שיעורי', 'בית']);
    assert.deepEqual(words('מבחן בתנ"ך'), ['מבחנ', 'בתנכ']);
    assert.deepEqual(words('חנ"ג'), ['חנג']);
  });
  test('ש.ב צמוד לאותיות אחרות אינו קיצור', () => {
    assert.equal(cleanText('אש.בר').includes('שיעורי בית'), false);
  });
  test('ניקוד, סימני כיווניות ופיסוק לא משפיעים', () => {
    assert.deepEqual(words('מִבְחָן‏ מחר!'), ['מבחנ', 'מחר']);
  });
  test('מספרים, שעות ותאריכים נשארים מילה אחת; מקף ואותיות מפרידים', () => {
    assert.deepEqual(words('ב-13:25'), ['ב', '13:25']);
    assert.deepEqual(words('שיעורים 8 ו-9'), ['שיעורימ', '8', 'ו', '9']);
    assert.deepEqual(words('בתאריך 6.10.2026.'), ['בתאריכ', '6.10.2026']);
    assert.deepEqual(words('ט6'), ['ט', '6']);
  });
  test('המיקום במחרוזת הנקייה נשמר', () => {
    const { clean, tokens } = tokenize('מבחן מחר');
    assert.equal(clean.slice(tokens[1].start, tokens[1].end), 'מחר');
  });
  test('קלט שאינו טקסט לא זורק', () => {
    assert.deepEqual(tokenize(undefined).tokens, []);
    assert.deepEqual(tokenize(null).tokens, []);
  });
});

