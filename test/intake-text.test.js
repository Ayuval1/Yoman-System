describe('intake-text: שורשים - מילים תמימות שלא נתפסות', () => {
  // מילים נפוצות שנראות כמו הטיה של שורש ולא אמורות לחשוב כך (ההשמטות המכוונות בטבלה).
  const negatives = {
    קבע: ['קבוע', 'קבועה'],
    הכניס: ['נכנס', 'נכנסים', 'הכנסת', 'הכניסה'],
    זכר: ['מזכירות', 'זיכרון', 'זכרון'],
    העביר: ['העברת', 'עברית', 'עבר'],
    הקדים: ['מוקדם', 'קדימה', 'הקדמה'],
    שינה: ['שינה', 'שונה', 'שנה', 'שינוי'],
    עדכן: ['עדכון'],
    הסיר: ['סיר', 'אסיר', 'הסירה', 'הסרט'],
    פתח: ['פתוח', 'פתוחה'],
    ראה: ['נראה', 'מראה'],
    אמר: ['אמור', 'נאמר'],
    הציג: ['נציג', 'הצגה'],
    הגיד: ['נגיד'],
    הביא: ['הבא', 'הבאה'],
    דחה: ['דחוף', 'דחיפות'],
    סיים: ['סימן', 'סימנו'],
  };
  for (const [root, forms] of Object.entries(negatives)) {
    test(`שורש ${root}`, () => {
      for (const form of forms) assert.equal(matchesRoot(root, tokenize(form).tokens[0].w), false, `${root}: ${form}`);
    });
  }
  test('שם פועל דורש ל\' - "קבוע" בלי ל\' אינו שם פועל', () => {
    assert.equal(matchesInfinitive('קבע', 'לקבוע'), true);
    assert.equal(matchesInfinitive('קבע', 'קבוע'), false);
    assert.equal(matchesInfinitive('קבע', 'ולקבוע'), true);
  });
  test('שורש לא מוכר זורק', () => {
    assert.throws(() => matchesRoot('אין-כזה', 'מילה'), RangeError);
    assert.throws(() => matchesInfinitive('אין-כזה', 'מילה'), RangeError);
  });
});

describe('intake-text: טבלת השורשים', () => {
  test('לכל שורש יש צורה לפחות', () => {
    for (const [root, spec] of Object.entries(ROOTS)) {
      assert.ok((spec.finite?.length ?? 0) + (spec.infinitive?.length ?? 0) > 0, root);
    }
  });
  test('nounRegex תופס קידומות של שם עצם', () => {
    const re = nounRegex('מבחן');
    for (const form of ['מבחן', 'המבחן', 'במבחן', 'למבחן', 'מהמבחן', 'והמבחן', 'שבמבחן', 'כשהמבחן']) assert.equal(re.test(fin(form)), true, form);
    assert.equal(re.test(fin('מבחנים')), false);
  });
});
