// בלוק 4, "74 שיעורים והפסקות ביומן" (docs/08-chapter8/35-chapter8-plan.md 8.4; docs/02-rules/03-google-calendar-rules.md, "שיעורים והפסקות — אירוע נפרד לכל אחד"
// ו"ההכרעה" על חיתוך חמש הסדרות הישנות). כאן רק פונקציות טהורות: בלי רשת ובלי מסד. הכתיבה עצמה: lib/ops/school-series.js.
//
// מה נבנה: כל שיעור = סדרה שבועית נפרדת (כותרת = מקצוע, מיקום = חדר, תיאור = מורה + רמה), כל הפסקה = סדרה שבועית נפרדת ("הפסקה").
// הפסקה = רווח בין שני שיעורים רצופים שיש באותו יום. לכן אין הפסקה בין 8 ל-9 (אין רווח) ואין הפסקה אחרי השיעור האחרון. צפוי 41 + 33 = 74.
// "לא ידוע" במורה או בחדר כבר נשמר כ-null ב-lib/timetable.js ("תחומי בחירה" בחמישי 3-4), ולכן נשאר ריק כאן.
//
// חזרה (H19): RRULE:FREQ=WEEKLY עם UNTIL ב-UTC, ושורת EXDATE;TZID=Asia/Jerusalem לכל יום חופשה, start/end עם timeZone 'Asia/Jerusalem' ושעת קיר בלי היסט.
// אומת מול התיעוד הרשמי של Google (נבדק ע"י המנהל, 22.11.2026; מדווח, לא נקרא על ידי בסשן הזה):
//   https://developers.google.com/workspace/calendar/api/v3/reference/events
//   https://developers.google.com/workspace/calendar/api/guides/recurringevents
//   https://developers.google.com/workspace/calendar/api/concepts/events-calendars
// - recurrence[] מקבל שורות RRULE/EXDATE לפי RFC 5545, בלי DTSTART (ההתחלה ב-start/end).
// - start.timeZone חובה באירוע חוזר; dateTime בלי היסט מותר כש-timeZone מוגדר.
// - EXDATE "must point to a valid instance generated by the recurrence rule": שעת ה-EXDATE חייבת להיות בדיוק שעת ההתחלה של הסדרה (נבדק ב-test/school-google.test.js).
// - אסור COUNT יחד עם UNTIL (ולכן planCut מוציא COUNT).
// - מזהה משלנו מותר: base32hex באותיות קטנות (a-v, 0-9), אורך 5 עד 1024, ייחודי ביומן. למופעים מזהים אחרים שחולקים iCalUID.
// לפי RFC 5545 §3.3.10: כש-DTSTART עם TZID, UNTIL חייב להיות ב-UTC (סיומת Z); לאירוע של יום שלם UNTIL הוא תאריך בלבד.
// לא כתוב בתיעוד (הנחה, לא אומת): (1) ש-PATCH של UNTIL חותך סדרה ושומר את מופעי העבר; (2) שמופעים יורשים את extendedProperties של הסדרה
// (לכן isAppSeriesEvent ב-lib/google.js מזהה גם לפי קידומת המזהה ו-recurringEventId).
//
// כותרת יום (22.11, בקשת יובל): מעל כל יום לימודים סדרה של יום שלם "🏫 בית ספר · HH:MM–HH:MM" (השיעור הראשון עד סוף האחרון), תיאור = רשימת השיעורים.
// חמש סדרות נוספות, נפרדות מ-74: countSeries סופר רק שיעורים והפסקות. אותם כללי חזרה (יום ראשון, UNTIL, חופשות), אבל בפורמט יום שלם:
// start.date / end.date (למחרת), UNTIL=YYYYMMDD (RFC 5545 §3.3.10: DTSTART מסוג DATE = UNTIL מסוג DATE), EXDATE;VALUE=DATE:YYYYMMDD,...
// הנחה, לא אומת: ש-Google מקבל timeZone לצד date (נשלח כמו בשאר הסדרות, כי timeZone חובה באירוע חוזר).
import { LESSON_PERIODS, subjectLabel } from './timetable.js';
import { addDays, weekdayOf } from './intake-dates.js';
import { zonedToUtc } from './schedule-time.js';
import { APP_PROPERTY, SCHOOL_SERIES_TAG, SCHOOL_SERIES_ID_PREFIX, isAppSeriesEvent } from './google.js';
import { VACATIONS, vacationOn } from './school-calendar.js';

export const SCHOOL_CALENDAR = 'בית ספר';
export const TIME_ZONE = 'Asia/Jerusalem';
export const BREAK_TITLE = 'הפסקה';
export const EXPECTED_COUNTS = Object.freeze({ lessons: 41, breaks: 33, total: 74 });
export const HEADER_TITLE_PREFIX = '🏫 בית ספר · ';
const OLD_SERIES_PREFIX = 'בית ספר יום';
const BYDAY = ['SU', 'MO', 'TU', 'WE', 'TH', 'FR', 'SA']; // לפי weekday-1 (1 = ראשון)

// רמה לפי שם המקצוע במערכת השעות. מקור: data/school-subjects-teachers.md (רק ארבעה מקצועות מסומנים "5 יח"ל"), והפיצולים מהערות
// data/school-timetable-taf-shin-pe-zayin.md ("גיאומטריה ומתמטיקה (תרגול) הן פיצולים של מתמטיקה"; "פיזיקה וכימיה הן פיצולים של מדעים").
// למקצוע אחר אין רמה בקבצים, ולכן אין רמה בתיאור (לא משלימים). בדיקה ב-test/school-google.test.js משווה לקובץ.
export const SUBJECT_LEVELS = Object.freeze({
  'אנגלית': '5 יח"ל',
  'מתמטיקה': '5 יח"ל',
  'גיאומטריה': '5 יח"ל',
  'מתמטיקה (תרגול)': '5 יח"ל',
  'פיזיקה': '5 יח"ל',
  'כימיה': '5 יח"ל',
  'מדעי המחשב': '5 יח"ל',
});

const endOfYearOf = (vacations) => vacations.find((v) => v?.endOfYear === true)?.from ?? null;
const DEFAULT_SCHOOL_YEAR = Number(String(endOfYearOf(VACATIONS) ?? '').slice(0, 4)) || null;

// מזהה Google קבוע לסדרה: base32hex (0-9, a-v), ולכן הרצה חוזרת פוגעת באותו מזהה ולא יוצרת כפילות. 'l' = שיעור, 'b' = הפסקה (אחרי שיעור period).
export function schoolEventId(year, weekday, period, kind) {
  return `${SCHOOL_SERIES_ID_PREFIX}${year}d${weekday}p${period}${kind === 'break' ? 'b' : 'l'}`;
}
// כותרת יום: 'hdr' במקום 'p<שיעור>', ולכן לא יכול להתנגש באף אחד מ-74 המזהים (שבכולם 'p' אחרי היום). h, d, r בטווח a-v.
export function schoolHeaderId(year, weekday) {
  return `${SCHOOL_SERIES_ID_PREFIX}${year}d${weekday}hdr`;
}

function lessonDescription(slot, levels) {
  const lines = [];
  if (slot.teacher) lines.push(`מורה: ${slot.teacher}`);
  if (levels[slot.subject]) lines.push(`רמה: ${levels[slot.subject]}`);
  return lines.length > 0 ? lines.join('\n') : null;
}

// timetable: { slots } כמו ב-lib/timetable.js. dayStructure: שיעורים { period, startsAt, endsAt } (ברירת מחדל: LESSON_PERIODS, שמושווה ל-data/school-day-structure.md).
// מחזיר רשימה ממוינת לפי יום ושעה: { key, eventId, weekday, period, kind, title, startsAt, endsAt, location, description }.
export function buildSchoolSeries(timetable, dayStructure = LESSON_PERIODS, subjectsInfo = SUBJECT_LEVELS, { schoolYear = DEFAULT_SCHOOL_YEAR } = {}) {
  const slots = Array.isArray(timetable?.slots) ? timetable.slots : [];
  const timesOf = new Map(dayStructure.map((p) => [p.period, p]));
  const series = [];
  for (const weekday of [...new Set(slots.map((s) => s.weekday))].sort((a, b) => a - b)) {
    const day = slots.filter((s) => s.weekday === weekday).sort((a, b) => a.period - b.period);
    day.forEach((slot, index) => {
      const times = timesOf.get(slot.period) ?? slot;
      series.push({
        key: `${weekday}-${slot.period}-lesson`, eventId: schoolEventId(schoolYear, weekday, slot.period, 'lesson'), weekday, period: slot.period, kind: 'lesson',
        title: subjectLabel(slot.subject), startsAt: times.startsAt, endsAt: times.endsAt, location: slot.room ?? null, description: lessonDescription(slot, subjectsInfo),
      });
      const next = day[index + 1];
      if (!next || next.period !== slot.period + 1) return;
      const nextTimes = timesOf.get(next.period) ?? next;
      if (times.endsAt >= nextTimes.startsAt) return; // אין רווח = אין הפסקה (8 ל-9)
      series.push({
        key: `${weekday}-${slot.period}-break`, eventId: schoolEventId(schoolYear, weekday, slot.period, 'break'), weekday, period: slot.period, kind: 'break',
        title: BREAK_TITLE, startsAt: times.endsAt, endsAt: nextTimes.startsAt, location: null, description: null,
      });
    });
  }
  return series;
}

// כותרות היום, נגזרות מהשיעורים של buildSchoolSeries (לא מהמערכת ישירות), כדי שהשעות והחדרים יהיו בדיוק אלה שביומן.
// שורה בתיאור לכל שיעור: "שיעור · התחלה–סוף · מקצוע · חדר X" (חדר רק כשיש). בלי מורים ובלי הפסקות.
export function buildSchoolHeaders(series, { schoolYear = DEFAULT_SCHOOL_YEAR } = {}) {
  const lessons = series.filter((s) => s.kind === 'lesson');
  return [...new Set(lessons.map((s) => s.weekday))].sort((a, b) => a - b).map((weekday) => {
    const day = lessons.filter((s) => s.weekday === weekday).sort((a, b) => a.period - b.period);
    const lines = day.map((s) => [s.period, `${s.startsAt}–${s.endsAt}`, s.title, ...(s.location ? [`חדר ${s.location}`] : [])].join(' · '));
    return {
      key: `${weekday}-header`, eventId: schoolHeaderId(schoolYear, weekday), weekday, period: null, kind: 'header', allDay: true,
      title: `${HEADER_TITLE_PREFIX}${day[0].startsAt}–${day[day.length - 1].endsAt}`, startsAt: day[0].startsAt, endsAt: day[day.length - 1].endsAt,
      location: null, description: lines.join('\n'),
    };
  });
}

// ספירה מול 74 (Plan B של 8.4: פער = עצירה). mismatch מראה בדיוק מה שונה. רק שיעורים והפסקות; כותרת יום לא נספרת.
export function countSeries(series) {
  const by_weekday = {};
  let lessons = 0;
  let breaks = 0;
  for (const item of series) {
    if (item.kind !== 'lesson' && item.kind !== 'break') continue;
    by_weekday[item.weekday] ??= { lessons: 0, breaks: 0 };
    if (item.kind === 'lesson') { lessons += 1; by_weekday[item.weekday].lessons += 1; } else { breaks += 1; by_weekday[item.weekday].breaks += 1; }
  }
  const total = lessons + breaks;
  const ok = lessons === EXPECTED_COUNTS.lessons && breaks === EXPECTED_COUNTS.breaks;
  const mismatch = ok ? null : `lessons=${lessons}/${EXPECTED_COUNTS.lessons} breaks=${breaks}/${EXPECTED_COUNTS.breaks} total=${total}/${EXPECTED_COUNTS.total}`;
  return { lessons, breaks, total, ok, mismatch, by_weekday };
}

const compactDate = (iso) => iso.replace(/-/g, '');
const compactTime = (hhmm) => `${hhmm.replace(':', '')}00`;
// Date -> YYYYMMDDTHHMMSSZ
const utcStamp = (date) => date.toISOString().replace(/[-:]/g, '').replace(/\.\d{3}/, '');

// חזרה של סדרה אחת: המופע הראשון = יום הלימודים הראשון באותו יום בשבוע מ-fromDate והלאה (לא בחופשה). UNTIL = יום לפני endOfYear, 23:59:59 בישראל.
// exdates = כל תאריך באותו יום בשבוע שנופל בחופשה, בין המופע הראשון ל-UNTIL. null = אין endOfYear בקובץ, או אין אף מופע.
export function seriesSchedule(item, { fromDate, vacations = VACATIONS }) {
  const endOfYear = endOfYearOf(vacations);
  if (!endOfYear) return null;
  let date = fromDate;
  while (weekdayOf(date) + 1 !== item.weekday) date = addDays(date, 1);
  while (date < endOfYear && vacationOn(date, vacations) !== null) date = addDays(date, 7);
  if (date >= endOfYear) return null;
  const firstDate = date;
  const exdates = [];
  for (let d = addDays(firstDate, 7); d < endOfYear; d = addDays(d, 7)) {
    if (vacationOn(d, vacations) !== null) exdates.push(d);
  }
  // יום שלם (כותרת): UNTIL בתאריך בלבד, היום שלפני endOfYear.
  const until = item.allDay ? compactDate(addDays(endOfYear, -1)) : utcStamp(new Date(zonedToUtc(endOfYear, '00:00', TIME_ZONE).getTime() - 1000));
  return { firstDate, until, exdates };
}

// גוף האירוע ל-Google (יצירה). מיקום ותיאור רק כשיש. התגית הפרטית מזהה את האירוע כשל האפליקציה.
export function seriesEventBody(item, schedule) {
  const body = { summary: item.title };
  if (item.location) body.location = item.location;
  if (item.description) body.description = item.description;
  if (item.allDay) {
    // יום שלם: end.date הוא היום שאחרי (בלעדי), כמו ב-Google.
    body.start = { date: schedule.firstDate, timeZone: TIME_ZONE };
    body.end = { date: addDays(schedule.firstDate, 1), timeZone: TIME_ZONE };
  } else {
    body.start = { dateTime: `${schedule.firstDate}T${item.startsAt}:00`, timeZone: TIME_ZONE };
    body.end = { dateTime: `${schedule.firstDate}T${item.endsAt}:00`, timeZone: TIME_ZONE };
  }
  body.recurrence = recurrenceLines(item, schedule);
  body.extendedProperties = { private: { [APP_PROPERTY]: SCHOOL_SERIES_TAG, key: item.key } };
  return body;
}

function recurrenceLines(item, schedule) {
  if (item.allDay) {
    const rrule = `RRULE:FREQ=WEEKLY;BYDAY=${BYDAY[item.weekday - 1]};UNTIL=${schedule.until}`;
    return schedule.exdates.length > 0 ? [rrule, `EXDATE;VALUE=DATE:${schedule.exdates.map(compactDate).join(',')}`] : [rrule];
  }
  return [
    `RRULE:FREQ=WEEKLY;BYDAY=${BYDAY[item.weekday - 1]};UNTIL=${schedule.until}`,
    ...schedule.exdates.map((d) => `EXDATE;TZID=${TIME_ZONE}:${compactDate(d)}T${compactTime(item.startsAt)}`),
  ];
}

// עדכון סדרה שכבר קיימת: כל השדות חוץ מ-start/end (ההתחלה המקורית נשמרת, כדי שמופעי העבר לא ייעלמו). החזרה מחושבת מתאריך ההתחלה המקורי,
// כך שחופשה שכבר עברה נשארת מוחרגת. location/description ריקים נשלחים כ-null כדי לנקות ערך ישן.
// הנחה, לא אומת: ש-PATCH עם location: null מנקה את השדה ב-Google.
function seriesPatch(item, schedule) {
  return {
    summary: item.title,
    location: item.location ?? null,
    description: item.description ?? null,
    recurrence: recurrenceLines(item, schedule),
    extendedProperties: { private: { [APP_PROPERTY]: SCHOOL_SERIES_TAG, key: item.key } },
  };
}

// סדרה קיימת שכבר זהה לעדכון: לא כותבים (הרצה חוזרת = אפס עדכונים). ריק ו-null נחשבים אותו דבר.
// הנחה, לא אומת: ש-Google מחזיר את שורות recurrence בדיוק כפי שנשלחו. אם לא, הסדרה פשוט תתעדכן שוב לאותו ערך (בלי נזק).
function seriesMatches(event, patch) {
  const same = (a, b) => (a || null) === (b || null);
  const priv = event?.extendedProperties?.private ?? {};
  return same(event.summary, patch.summary) && same(event.location, patch.location) && same(event.description, patch.description)
    && JSON.stringify(event.recurrence ?? []) === JSON.stringify(patch.recurrence)
    && priv[APP_PROPERTY] === patch.extendedProperties.private[APP_PROPERTY] && priv.key === patch.extendedProperties.private.key;
}

// התאריך (YYYY-MM-DD) של התחלת אירוע מ-Google, לפי השעה המקומית שכתובה בו. null אם אין.
function startDateOf(event) {
  const value = event?.start?.dateTime ?? event?.start?.date;
  return typeof value === 'string' && /^\d{4}-\d{2}-\d{2}/.test(value) ? value.slice(0, 10) : null;
}

// אחת מחמש הסדרות הישנות: סדרה (RRULE) שהכותרת שלה מתחילה ב"בית ספר יום", ושאינה של האפליקציה. רק אלה נחתכות, ושום דבר אחר.
// הכותרת מנורמלת לפני ההשוואה: סימני כיוון (RLM/LRM וכו'), רווחים מיוחדים, מקף ומקף עברי בין "בית ספר" ל"יום" לא מפילים את הזיהוי.
// (22.11: ההרצה היבשה לא מצאה אף סדרה ישנה, ויובל אישר שהן ביומן.)
export function normalizeTitle(text) {
  if (typeof text !== 'string') return '';
  return text.replace(/[\u200e\u200f\u202a-\u202e\u2066-\u2069\ufeff]/g, '')
    .replace(/[-\u05be\u2010-\u2015:,]/g, ' ')
    .replace(/[\s\u00a0]+/g, ' ')
    .trim();
}
export function isOldSchoolSeries(event) {
  if (!event || event.status === 'cancelled' || isAppSeriesEvent(event)) return false;
  if (!normalizeTitle(event.summary).startsWith(OLD_SERIES_PREFIX)) return false;
  return Array.isArray(event.recurrence) && event.recurrence.some((line) => line.startsWith('RRULE:'));
}

// חיתוך סדרה ישנה ביום ההפעלה: UNTIL = יום לפני ההפעלה, 23:59:59 בישראל (העבר נשמר, העתיד נעלם). COUNT יוצא (אסור יחד עם UNTIL ב-RFC 5545).
// שאר השורות (EXDATE וכו') נשמרות כמו שהן. לא מוחקים לעולם.
// הנחה, לא אומת: ש-PATCH של recurrence בלבד חותך את הסדרה ב-Google ומשאיר את מופעי העבר (03-google-calendar-rules.md: "לא אומת").
export function planCut(event, activationDate) {
  const start = startDateOf(event);
  if (start !== null && start >= activationDate) return { action: null, reason: 'starts_after_activation' };
  const allDay = typeof event?.start?.date === 'string' && !event?.start?.dateTime;
  const dayBefore = addDays(activationDate, -1);
  const until = allDay ? compactDate(dayBefore) : utcStamp(new Date(zonedToUtc(activationDate, '00:00', TIME_ZONE).getTime() - 1000));
  let changed = false;
  let alreadyCut = false;
  const recurrence = event.recurrence.map((line) => {
    if (!line.startsWith('RRULE:')) return line;
    const parts = line.slice('RRULE:'.length).split(';').filter(Boolean);
    const existingUntil = parts.find((p) => p.startsWith('UNTIL='))?.slice('UNTIL='.length);
    if (existingUntil && existingUntil.slice(0, 8) < compactDate(activationDate)) {
      alreadyCut = true;
      return line;
    }
    changed = true;
    return `RRULE:${[...parts.filter((p) => !p.startsWith('UNTIL=') && !p.startsWith('COUNT=')), `UNTIL=${until}`].join(';')}`;
  });
  if (!changed) return { action: null, reason: alreadyCut ? 'already_cut' : 'no_rrule' };
  return { action: 'cut', recurrence };
}

// התכנית המלאה (טהור). existing = אירועי היומן "בית ספר" (listSeriesEvents). activationDate = התאריך הישראלי של ההפעלה.
// hiddenIds: מזהים קבועים שנמצאו ב-Google כמבוטלים (יובל מחק). הם לא נוצרים מחדש בשקט: נכנסים ל-hidden, והקורא מדווח וחוסם חיתוך.
// series יכול לכלול גם כותרות יום (kind 'header'); הן מתוכננות בדיוק כמו שיעור. unchanged = קיימת וכבר זהה לעדכון, בלי כתיבה.
// מחזיר { create:[{ item, body }], update:[{ item, eventId, patch }], unchanged:[item], hidden:[item], cut:[{ event, recurrence }], cutSkipped:[{ event, reason }], orphans:[event], unscheduled:[item] }.
export function planSchoolSeries({ series, existing, activationDate, vacations = VACATIONS, hiddenIds = [] }) {
  const appEvents = existing.filter((e) => isAppSeriesEvent(e));
  const byId = new Map(appEvents.map((e) => [e.id, e]));
  const hidden = new Set(hiddenIds);
  const plan = { create: [], update: [], unchanged: [], hidden: [], cut: [], cutSkipped: [], orphans: [], unscheduled: [] };
  const wanted = new Set();
  for (const item of series) {
    wanted.add(item.eventId);
    if (hidden.has(item.eventId)) { plan.hidden.push(item); continue; }
    const found = byId.get(item.eventId);
    const fromDate = found ? (startDateOf(found) ?? activationDate) : activationDate;
    const schedule = seriesSchedule(item, { fromDate, vacations });
    if (!schedule) { plan.unscheduled.push(item); continue; }
    if (found) {
      const patch = seriesPatch(item, schedule);
      if (seriesMatches(found, patch)) plan.unchanged.push(item);
      else plan.update.push({ item, eventId: found.id, patch });
    } else plan.create.push({ item, body: seriesEventBody(item, schedule), schedule });
  }
  plan.orphans = appEvents.filter((e) => !wanted.has(e.id));
  for (const event of existing.filter(isOldSchoolSeries)) {
    const cut = planCut(event, activationDate);
    if (cut.action === 'cut') plan.cut.push({ event, recurrence: cut.recurrence });
    else plan.cutSkipped.push({ event, reason: cut.reason });
  }
  return plan;
}
