// "ולקבוע", "שתקבע", "ביטלו" ו"מבוטלים" נתפסים, ואילו מחרוזות תמימות ("קבוע" בלי ל', "נכנס", "מוקדם") לא.
//
// [הנחה, לא אומת] טבלת הצורות נכתבה ידנית ולא נמדדה על מדגם מתויג (03-intake-rules.md:386 "אימות המילון" פתוח, שלב 8.8).
// כל צורה שנראתה דו-משמעית מול מילה נפוצה (נכנס, נציג, מוקדם, קדימה, הכנסת, הבא ועוד) הושמטה בכוונה, והשמטה כזו עלולה להחמיץ הודעה:
// החמצה נופלת לשאלה (בטוח), התאמת-יתר הייתה כותבת משהו שלא נאמר.

const FINALS = { ך: 'כ', ם: 'מ', ן: 'נ', ף: 'פ', ץ: 'צ' };

// אותיות סופיות לצורה רגילה, כדי שתבניות יכתבו פעם אחת (עדכן = עדכנ, גם בעדכנתי).
export const fin = (text) => text.replace(/[ךםןףץ]/g, (letter) => FINALS[letter]);

// ההפך, לתצוגה: האות האחרונה של מילה חוזרת לצורתה הסופית (בוחנ -> בוחן). רק האות האחרונה, כמו בכתיב העברי.
const TO_FINAL = { כ: 'ך', מ: 'ם', נ: 'ן', פ: 'ף', צ: 'ץ' };
export const unfin = (word) => word.replace(/[כמנפצ]$/, (letter) => TO_FINAL[letter]);

const INVISIBLE_MARKS = /[\u200B-\u200F\u202A-\u202E\u2066-\u2069\uFEFF]/g; // סימני כיווניות ו-BOM שמגיעים מהעתקה
const NIQQUD = /[\u0591-\u05C7]/g; // ניקוד וטעמים
const HEBREW = 'א-ת';
const QUOTES_INSIDE_WORD = new RegExp(`(?<=[${HEBREW}])["״'׳’](?=[${HEBREW}])`, 'g'); // תנ"ך, חנ"ג, ש"ח: מחברים
// "ש.ב" (שיעורי בית, 03-intake-rules.md:247) הופך למילים רגילות לפני הפיצול. ש.ב צמוד לאותיות אחרות לא נתפס.
const HOMEWORK_ABBREVIATION = new RegExp(`(?<![${HEBREW}])ש\\s*[.״"׳'’]\\s*ב(?![${HEBREW}])`, 'g');

export function cleanText(text) {
  return String(text ?? '')
    .normalize('NFC')
    .replace(INVISIBLE_MARKS, '')
    .replace(NIQQUD, '')
    .replace(HOMEWORK_ABBREVIATION, ' שיעורי בית ')
    .replace(QUOTES_INSIDE_WORD, '');
}

// מפצל למילים: אותיות עבריות, מספרים (גם 6.10, 13:25, 6/10) ומילים לטיניות. פיסוק ומקפים הם מפרידים.
// כל מילה: { w: הצורה המנורמלת (בלי סופיות), start, end } לפי המיקום במחרוזת הנקייה clean.
export function tokenize(text) {
  const clean = cleanText(text);
  const tokens = [];
  for (const match of clean.matchAll(/[א-ת]+|\d+(?:[.:/]\d+)*|[A-Za-z]+/g)) {
    tokens.push({ w: fin(match[0]), start: match.index, end: match.index + match[0].length });
  }
  return { clean, tokens };
}

// קידומות תחביריות. פועל מוטה: ו' / ש' / כש'. שם פועל: אותן קידומות וחובה ל'. שם עצם: ו'/ש'/כש' + ב/ל/מ/כ + ה'.
export const CLITIC = {
  verb: '(?:וכש|וש|כש|ו|ש)?',
  inf: '(?:וכש|וש|כש|ו|ש)?ל',
  noun: '(?:וכש|וש|כש|ו|ש)?(?:ב|ל|מ|כ)?ה?',
};

export const nounRegex = (body) => new RegExp(`^${CLITIC.noun}(?:${fin(body)})$`);
export const plainRegex = (body) => new RegExp(`^(?:${fin(body)})$`);

