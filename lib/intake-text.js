function compileRoot({ finite = [], infinitive = [] }) {
  const finiteBody = finite.map(fin).join('|');
  const infinitiveBody = infinitive.map(fin).join('|');
  const parts = [];
  if (finite.length) parts.push(`${CLITIC.verb}(?:${finiteBody})`);
  if (infinitive.length) parts.push(`${CLITIC.inf}(?:${infinitiveBody})`);
  return {
    any: new RegExp(`^(?:${parts.join('|')})$`),
    inf: infinitive.length ? new RegExp(`^${CLITIC.inf}(?:${infinitiveBody})$`) : null,
  };
}

const COMPILED = Object.fromEntries(Object.entries(ROOTS).map(([root, spec]) => [root, compileRoot(spec)]));

// האם המילה w (כבר מנורמלת) היא צורה כלשהי של השורש.
export function matchesRoot(root, w) {
  const compiled = COMPILED[root];
  if (!compiled) throw new RangeError(`matchesRoot: שורש לא מוכר: ${root}`);
  return typeof w === 'string' && compiled.any.test(w);
}

// האם המילה היא שם הפועל של השורש (עם ל'): "להביא", "לקחת".
export function matchesInfinitive(root, w) {
  const compiled = COMPILED[root];
  if (!compiled) throw new RangeError(`matchesInfinitive: שורש לא מוכר: ${root}`);
  return compiled.inf !== null && typeof w === 'string' && compiled.inf.test(w);
}

export const isNumberWord = (w) => typeof w === 'string' && /^\d+$/.test(w);
